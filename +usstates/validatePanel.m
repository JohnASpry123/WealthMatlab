function years = validatePanel(data)
% Validate persisted data as strictly as newly downloaded data.
[fips,names] = usstates.states();
fields = cellfun(@matlab.lang.makeValidName,names,'UniformOutput',false);
assert(isstruct(data) && isscalar(data) && isequal(sort(fieldnames(data)),sort(fields)), ...
    'usstates:States','Dataset must contain exactly the 50 named states.');
years = data.(fields{1}).year;
assert(isnumeric(years) && iscolumn(years) && ~isempty(years) && ...
    isequal(years,usstates.years(years(1),years(end))), ...
    'usstates:Years','Dataset years must be contiguous and increasing.');
variables = {'Y','pop','pop_w','y_pop','y_w'};
for i=1:50
    d = data.(fields{i});
    assert(all(isfield(d,[{'state','fips','year'},variables])) && ...
        strcmp(d.state,names{i}) && isequal(d.fips,fips(i)) && isequal(d.year,years), ...
        'usstates:Alignment','State identity or year alignment is invalid.');
    for j=1:numel(variables)
        x = d.(variables{j});
        assert(isnumeric(x) && isreal(x) && isequal(size(x),size(years)) && all(isfinite(x) & x>0), ...
            'usstates:Values','Invalid %s for %s.',variables{j},names{i});
    end
    assert(all(d.pop_w<=d.pop) && all(d.pop==fix(d.pop)) && all(d.pop_w==fix(d.pop_w)), ...
        'usstates:Population','Invalid resident population counts.');
    assert(all(abs(d.y_pop-d.Y./d.pop)<=1e-10*max(1,d.Y./d.pop)) && ...
        all(abs(d.y_w-d.Y./d.pop_w)<=1e-10*max(1,d.Y./d.pop_w)), ...
        'usstates:Identity','GDP per-person identities do not hold.');
end
end
